#!/usr/bin/env python3
"""Phase 0 validation of the tone and hate scores against a labelled sample (read-only).

Input : data/calibration/labelled_sample.parquet   (post text + model scores + labels; NOT committed)
Output: reports/TONE_HATE_VALIDATION.md             (numbers only, no post text)

Labels (drafted blind to the model scores by the assistant; a single labeller, NOT yet confirmed by a human):
  label_tone         -1 / 0 / +1   expressed sentiment of the text; purely factual reporting = 0
  label_hate         1 if the text contains abusive or hateful language (slurs, dehumanising or strong
                     insults, threats, calls for harm) aimed at a person or group; else 0
  factual_report     1 if the text is a factual report without evaluative language
  profane_or_insult  1 if the text has profanity or an insult (even if not aimed at a target)

Sample design: 192 original rows (12 per platform) + top-up rows (thin languages; hate-score strata).
Tone accuracy uses original rows + language strata only (the hate strata are biased towards toxic text).
Hate precision/recall is estimated per hate-score band and re-weighted by band size in the corpus.

Run:  .venv/bin/python scripts/validate_tone_hate.py
"""
from __future__ import annotations

from pathlib import Path

import duckdb
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SAMPLE = ROOT / "data" / "calibration" / "labelled_sample.parquet"
OUT = ROOT / "reports" / "TONE_HATE_VALIDATION.md"
BANDS = [(-1, 0.1, "<0.1"), (0.1, 0.5, "0.1-0.5"), (0.5, 0.9, "0.5-0.9"), (0.9, 1.01, ">=0.9")]


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (np.nan, np.nan)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def cls(t: pd.Series, th: float) -> np.ndarray:
    return np.where(t > th, 1, np.where(t < -th, -1, 0))


def macro_f1(y: np.ndarray, p: np.ndarray) -> float:
    f = []
    for c in (-1, 0, 1):
        tp = int(((p == c) & (y == c)).sum()); fp = int(((p == c) & (y != c)).sum()); fn = int(((p != c) & (y == c)).sum())
        f.append(0.0 if tp == 0 else 2 * tp / (2 * tp + fp + fn))
    return float(np.mean(f))


def kappa(y: np.ndarray, p: np.ndarray) -> float:
    po = float((y == p).mean())
    pe = sum(float((y == c).mean()) * float((p == c).mean()) for c in (-1, 0, 1))
    return (po - pe) / (1 - pe) if pe < 1 else np.nan


def main() -> int:
    D = pd.read_parquet(SAMPLE)
    D["band"] = pd.cut(D.hate_score, [b[0] for b in BANDS] + [BANDS[-1][1]], labels=[b[2] for b in BANDS], right=True)
    L: list[str] = []
    A = L.append
    A("# Tone and hate validation (Phase 0)\n")
    A("Single-labeller draft, blind to the model scores, NOT yet confirmed by a human. "
      "Numbers only; no post text. Generated by `scripts/validate_tone_hate.py`.\n")
    A(f"Sample: {len(D)} posts ({(D.stratum == 'original_192').sum()} original, "
      f"{(D.stratum != 'original_192').sum()} top-up). Label counts: tone {D.label_tone.value_counts().sort_index().to_dict()}, "
      f"hate {D.label_hate.value_counts().sort_index().to_dict()}.\n")

    # ------------------------------------------------------------------ tone
    T = D[~D.stratum.str.startswith("hate:")].copy()          # original + language strata
    y = T.label_tone.to_numpy()
    A("## Tone (model class from tone_score vs label)\n")
    A(f"Rows used: {len(T)} (original 192 + language top-ups; hate strata excluded because they are biased to toxic text).\n")
    A("| threshold | accuracy | macro-F1 | kappa | neutral share (model) |")
    A("|---|---|---|---|---|")
    best = None
    for th in (0.05, 0.10, 0.15, 0.25, 0.35, 0.50):
        p = cls(T.tone_score, th)
        acc = float((p == y).mean()); f1 = macro_f1(y, p)
        if best is None or f1 > best[1]:
            best = (th, f1)
        A(f"| ±{th:.2f} | {acc:.3f} | {f1:.3f} | {kappa(y, p):.3f} | {(p == 0).mean():.3f} |")
    A(f"\nBest macro-F1 on this sample: threshold ±{best[0]:.2f} (the pipeline's planned NSS cut-off is ±0.15).\n")
    p = cls(T.tone_score, 0.15)
    cm = pd.crosstab(pd.Series(y, name="label"), pd.Series(p, name="model"))
    A("Confusion matrix at ±0.15 (rows = label, columns = model):\n")
    A("```\n" + cm.to_string() + "\n```\n")
    rho = pd.Series(T.tone_score.to_numpy()).corr(pd.Series(y), method="spearman")
    A(f"Spearman correlation tone_score vs label: {rho:.3f}\n")
    A("### By text type (±0.15)\n")
    A("| subset | n | accuracy |")
    A("|---|---|---|")
    for name, m in [("factual report (label 0 expected)", T.factual_report == 1), ("opinion / emotive", T.factual_report == 0)]:
        s = T[m]
        A(f"| {name} | {len(s)} | {float((cls(s.tone_score, 0.15) == s.label_tone.to_numpy()).mean()):.3f} |")
    fr = T[T.factual_report == 1]
    A(f"\nOf {len(fr)} factual reports, the model calls {(cls(fr.tone_score, 0.15) == -1).mean():.0%} negative and "
      f"{(cls(fr.tone_score, 0.15) == 1).mean():.0%} positive (labelled neutral). Negative events reported factually are scored negative.\n")
    A("### By platform (original 192 rows only, 12 per platform; indicative)\n")
    O = D[D.stratum == "original_192"]
    A("| platform | n | accuracy | mean model tone | mean label |")
    A("|---|---|---|---|---|")
    for pl, s in O.groupby("platform"):
        A(f"| {pl} | {len(s)} | {float((cls(s.tone_score, 0.15) == s.label_tone.to_numpy()).mean()):.2f} | "
          f"{s.tone_score.mean():+.2f} | {s.label_tone.mean():+.2f} |")
    A("\n### By language (language top-ups; n is small, indicative only)\n")
    A("| language | n | accuracy |")
    A("|---|---|---|")
    for lg, s in D[D.stratum.str.startswith("lang:")].groupby("stratum"):
        A(f"| {lg[5:]} | {len(s)} | {float((cls(s.tone_score, 0.15) == s.label_tone.to_numpy()).mean()):.2f} |")
    nss_l = 100 * float((O.label_tone == 1).mean() - (O.label_tone == -1).mean())
    nss_m = 100 * float((cls(O.tone_score, 0.15) == 1).mean() - (cls(O.tone_score, 0.15) == -1).mean())
    A(f"\nNSS on the original 192 rows: labels {nss_l:+.1f}, model {nss_m:+.1f}.\n")

    # ------------------------------------------------------------------ hate
    con = duckdb.connect(str(ROOT / "data" / "analytics.duckdb"), read_only=True)
    pop = con.execute("SELECT hate_score h FROM post_scores WHERE hate_valid").fetchdf().h
    con.close()
    N = {b[2]: int(((pop > b[0]) & (pop <= b[1])).sum()) for b in BANDS}
    A("## Hate / toxicity (raw hate_score vs label_hate)\n")
    A("label_hate = abusive or hateful language aimed at a person or group. profane_or_insult is any profanity or insult.\n")
    A("| hate_score band | corpus posts | sample n | labelled hate | rate (95% CI) | any profanity/insult | factual report |")
    A("|---|---|---|---|---|---|---|")
    est = {}
    for _, _, name in BANDS:
        s = D[D.band == name]
        k = int(s.label_hate.sum()); n = len(s)
        lo, hi = wilson(k, n)
        est[name] = (k / n if n else np.nan, N[name])
        A(f"| {name} | {N[name]:,} | {n} | {k} | {k / n:.2f} ({lo:.2f}-{hi:.2f}) | {s.profane_or_insult.mean():.2f} | {s.factual_report.mean():.2f} |")
    tot_pos = sum(r * n for r, n in est.values())
    A(f"\nEstimated hateful posts in the corpus (band rate x band size): about {tot_pos:,.0f} of {sum(N.values()):,} "
      f"({tot_pos / sum(N.values()):.2%}).\n")
    A("| flag when hate_score above | posts flagged | estimated precision | estimated recall |")
    A("|---|---|---|---|")
    names = [b[2] for b in BANDS]
    for th, first in ((0.1, 1), (0.5, 2), (0.9, 3)):
        flagged = sum(est[n][1] for n in names[first:])
        tp = sum(est[n][0] * est[n][1] for n in names[first:])
        A(f"| {th} | {flagged:,} | {tp / flagged:.2f} | {tp / tot_pos:.2f} |")
    hi_ = D[D.hate_score > 0.5]
    fp = hi_[hi_.label_hate == 0]
    A(f"\nWhy high scores are not labelled hateful: of {len(hi_)} sampled posts above 0.5, {len(fp)} are not hate. "
      f"Among those: {int((fp.factual_report == 1).sum())} factual report, {int(((fp.profane_or_insult == 1) & (fp.factual_report == 0)).sum())} "
      f"profanity or insult without a target, {int(((fp.profane_or_insult == 0) & (fp.factual_report == 0)).sum())} other.\n")
    A("## Caveats\n")
    A("- One labeller (the assistant), blind to scores, not confirmed by a human. Treat every figure as provisional until a human reviewer checks at least a random subset.\n"
      "- Neutral-versus-opinion and hate-versus-insult boundaries are judgement calls; a different labeller could move the figures.\n"
      "- The text scored is `post_facts.text`: the translation where one exists, otherwise the original. Original-language text was not compared.\n"
      "- Language and platform cells are small (6 to 12 posts). They indicate where to label more, not measured accuracy.\n"
      "- Hate precision is re-weighted by band size from stratified samples. The top band has only 30 sampled posts.\n")
    OUT.write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
