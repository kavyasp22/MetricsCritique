#!/usr/bin/env python3
"""Checks C1-C4 on the published core signals (read-only on data/metrics.duckdb).

C1 weekday pattern in the surprise baseline   (does the baseline leave a weekday residual?)
C2 alert FDR: Benjamini-Hochberg vs Benjamini-Yekutieli (how many alerts survive the stricter correction?)
C3 burst detector sensitivity to s and gamma  (how stable are burst days?)
C4 momentum: what does EMA7-EMA21 of growth actually predict?

Output: reports/CORE_SIGNAL_CHECKS.md (numbers only, no post text).
Run:  .venv/bin/python scripts/review/core_signal_checks.py
"""
from __future__ import annotations

import sys
import warnings
from pathlib import Path

import duckdb
import numpy as np
import pandas as pd

warnings.filterwarnings("ignore")
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
from lib import stats_v2 as S  # noqa: E402

OUT = ROOT / "reports" / "CORE_SIGNAL_CHECKS.md"
DOW = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]


def main() -> int:
    con = duckdb.connect(str(ROOT / "data" / "metrics.duckdb"), read_only=True)
    d = con.execute(
        "SELECT day, topic_id, platform, V, baseline_mean, baseline_mu, surprise_p, alert_flag, growth, momentum, "
        "support_ok, burst_support_ok FROM metrics_daily WHERE in_window ORDER BY topic_id, platform, day").df()
    con.close()
    d["day"] = pd.to_datetime(d["day"])
    d["dow"] = d["day"].dt.dayofweek
    g = d[d["support_ok"].fillna(False) & (d["baseline_mu"] > 0)].copy()
    L: list[str] = ["# Core signal checks (C1-C4)\n",
                    f"Cells with support: {len(g):,} of {len(d):,} in-window cells. Generated by `scripts/review/core_signal_checks.py`.\n"]
    A = L.append

    # ---- C1 weekday
    g["r_raw"] = g["V"] / g["baseline_mean"]
    g["r_adj"] = g["V"] / g["baseline_mu"]
    t = g.groupby("dow").agg(n=("V", "size"), raw=("r_raw", "median"), adj=("r_adj", "median"),
                             p05=("surprise_p", lambda x: float((x < 0.05).mean())))
    A("## C1 Weekday pattern\n")
    A("Median of V / baseline. `raw` = trailing mean only; `adjusted` = the baseline actually used (effort offset + drift). "
      "p<0.05 is the share of cells with surprise_p below 0.05 (includes real events, so it is only a relative guide).\n")
    A("| day | cells | raw | adjusted | share p<0.05 |\n|---|---|---|---|---|")
    for i, r in t.iterrows():
        A(f"| {DOW[i]} | {int(r.n)} | {r.raw:.2f} | {r.adj:.2f} | {r.p05:.3f} |")
    wk = g[g.dow < 5]; we = g[g.dow >= 5]
    A(f"\nWeekend / weekday median ratio: raw {we.r_raw.median() / wk.r_raw.median():.2f}, "
      f"adjusted {we.r_adj.median() / wk.r_adj.median():.2f}.\n")

    # ---- C2 BH vs BY
    n = {"bh": 0, "by": 0}
    for _, x in g.groupby("day"):
        p = x["surprise_p"].to_numpy(float)
        for m in n:
            n[m] += int((S.bh_qvalues(p, method=m) < 0.05).sum())
    A("## C2 Alert FDR: BH versus BY\n")
    A(f"Alerts recomputed from the published p-values (per day): BH {n['bh']}, BY {n['by']} "
      f"({n['by'] / max(n['bh'], 1):.0%} survive the stricter correction). Published alert_flag count: {int(g.alert_flag.sum())} "
      "(uses mid-p values, so it differs slightly from BH on the published p).\n")

    # ---- C3 burst sensitivity
    def burst_days(s, gamma):
        out = set()
        for (tp, pl), x in d[d["burst_support_ok"].fillna(False)].groupby(["topic_id", "platform"]):
            r = S.detect_bursts(x["V"].to_numpy(float), s=s, gamma=gamma)
            st = np.asarray(r.state)
            out.update((tp, pl, dd) for dd, v in zip(x["day"], st) if v > 0)
        return out
    base = burst_days(2.0, 1.0)
    A("## C3 Burst sensitivity\n")
    A("Burst days over series with burst support, default s=2, gamma=1; overlap = Jaccard with the default.\n")
    A("| s | gamma | burst days | overlap with default |\n|---|---|---|---|")
    for s, gm in ((1.5, 1.0), (2.0, 0.5), (2.0, 1.0), (2.0, 2.0), (3.0, 1.0)):
        b = base if (s, gm) == (2.0, 1.0) else burst_days(s, gm)
        A(f"| {s} | {gm} | {len(b):,} | {len(b & base) / max(len(b | base), 1):.2f} |")

    # ---- C4 momentum
    d = d.sort_values(["topic_id", "platform", "day"])
    grp = d.groupby(["topic_id", "platform"])
    d["g_next"] = grp["growth"].shift(-1)
    d["g_next7"] = grp["growth"].transform(lambda x: x.shift(-1).rolling(7, min_periods=7).sum().shift(-6))
    m = d[d.momentum.notna() & d.support_ok.fillna(False)]
    A("\n## C4 Momentum (EMA7 minus EMA21 of daily growth)\n")
    A("Spearman correlation with future growth, and with the growth already seen that day:\n")
    A("| compared with | cells | Spearman |\n|---|---|---|")
    for lab, col in (("growth today (same day)", "growth"), ("growth next day", "g_next"), ("sum of growth, next 7 days", "g_next7")):
        mm = m[m[col].notna()]
        A(f"| {lab} | {len(mm):,} | {mm.momentum.corr(mm[col], method='spearman'):+.2f} |")
    mm = m[m.g_next.notna()]
    A(f"\nGrowth itself, today versus next day: {mm.growth.corr(mm.g_next, method='spearman'):+.2f} (daily growth reverses: a high day tends to be followed by a lower one).\n")
    A("Reading: momentum describes the recent direction of volume. It does not forecast the next day.\n")
    OUT.write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
