#!/usr/bin/env python3
"""Score a returned human review sheet against the draft labels and the model (read-only, numbers only).

Input : the filled Tone_Hate_Review_Sheet.xlsx (sheet 'Review'; column ID = row `idx` of the sample)
        data/calibration/labelled_sample.parquet   (model scores + the assistant's blind draft labels; NOT committed)
Output: reports/TONE_HUMAN_AGREEMENT.md            (counts and agreement figures only, no post text)

Reports, for tone / hate / factual-report:
  rows labelled by the human, percent agreement with the draft, Cohen's kappa, Krippendorff's alpha
  (nominal for all; interval for tone, where -1/0/+1 are ordered), and the tone confusion matrix.
Then the model's tone class (threshold sweep) against the HUMAN labels, the same table as TONE_HATE_VALIDATION.md.
Rows marked Unsure=Y or left blank are excluded from that label's figures and counted.

Run:  .venv/bin/python scripts/compare_human_labels.py path/to/returned_sheet.xlsx
"""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

import duckdb
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SAMPLE = ROOT / "data" / "calibration" / "labelled_sample.parquet"
OUT = ROOT / "reports" / "TONE_HUMAN_AGREEMENT.md"
THRESHOLDS = [0.05, 0.10, 0.15, 0.25, 0.35, 0.50]


def cohen_kappa(a, b) -> float:
    a, b = np.asarray(a), np.asarray(b)
    n = len(a)
    if n == 0:
        return float("nan")
    cats = sorted(set(a) | set(b))
    po = float(np.mean(a == b))
    pe = sum((np.mean(a == c)) * (np.mean(b == c)) for c in cats)
    return float("nan") if pe == 1 else (po - pe) / (1 - pe)


def krippendorff_alpha(a, b, metric: str = "nominal") -> float:
    """Two raters, no missing values (rows with a blank label are dropped before calling)."""
    vals = sorted(set(a) | set(b))
    idx = {v: i for i, v in enumerate(vals)}
    k = len(vals)
    o = np.zeros((k, k))
    for x, y in zip(a, b):          # coincidence matrix: every pair counted in both orders
        o[idx[x], idx[y]] += 1
        o[idx[y], idx[x]] += 1
    n = o.sum()
    if n <= 1:
        return float("nan")
    nc = o.sum(axis=1)
    def delta(i, j):
        if i == j:
            return 0.0
        return 1.0 if metric == "nominal" else float((vals[i] - vals[j]) ** 2)
    do = sum(o[i, j] * delta(i, j) for i in range(k) for j in range(k)) / n
    de = sum(nc[i] * nc[j] * delta(i, j) for i in range(k) for j in range(k)) / (n * (n - 1))
    return float("nan") if de == 0 else 1 - do / de


def load_human(path: Path) -> pd.DataFrame:
    df = pd.read_excel(path, sheet_name="Review", dtype=object)
    df = df.rename(columns={"ID": "idx", "Tone (-1 / 0 / 1)": "h_tone", "Hate (0 / 1)": "h_hate",
                            "Factual report (0 / 1)": "h_fact", "Unsure (Y)": "unsure"})
    df["idx"] = pd.to_numeric(df["idx"], errors="coerce")
    for c in ("h_tone", "h_hate", "h_fact"):
        df[c] = pd.to_numeric(df[c], errors="coerce")
    df["unsure"] = df["unsure"].astype(str).str.strip().str.upper().eq("Y")
    return df[["idx", "h_tone", "h_hate", "h_fact", "unsure"]].dropna(subset=["idx"])


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__)
        return 2
    human = load_human(Path(argv[1]))
    sample = duckdb.connect().execute(f"SELECT * FROM '{SAMPLE}'").df()
    D = sample.merge(human, on="idx", how="left")
    L = [f"# Human labels against the draft labels and the model\n",
         "Numbers only; generated by `scripts/compare_human_labels.py`. Sample rows: "
         f"{len(sample)}; rows the human returned: {int(D.h_tone.notna().sum() + 0)} with a tone label, "
         f"{int(D.unsure.sum())} marked unsure.\n"]

    for name, h, d in (("Tone (-1/0/+1)", "h_tone", "label_tone"), ("Hate (0/1)", "h_hate", "label_hate"),
                       ("Factual report (0/1)", "h_fact", "factual_report")):
        X = D[(~D.unsure) & D[h].notna()]
        a, b = X[h].astype(int).values, X[d].astype(int).values
        L.append(f"## {name}\n")
        L.append(f"Rows with both labels: {len(X)}  (excluded: {len(D) - len(X)} unsure or blank)")
        if len(X):
            L.append(f"- Agreement: {100 * np.mean(a == b):.1f}%")
            L.append(f"- Cohen's kappa (human vs draft): {cohen_kappa(a, b):.3f}")
            L.append(f"- Krippendorff's alpha, nominal: {krippendorff_alpha(a, b):.3f}")
            if h == "h_tone":
                L.append(f"- Krippendorff's alpha, interval (ordered -1/0/+1): {krippendorff_alpha(a, b, 'interval'):.3f}")
                cm = pd.crosstab(pd.Series(a, name="human"), pd.Series(b, name="draft"))
                L.append("\nConfusion (rows = human, columns = draft):\n\n```\n" + cm.to_string() + "\n```")
            L.append("")
    X = D[(~D.unsure) & D.h_tone.notna() & D.stratum.isin(["original_192"] + [s for s in D.stratum.unique() if str(s).startswith("lang")])]
    if len(X):
        L.append("## Model tone class against the HUMAN labels\n")
        L.append("| threshold | accuracy | kappa | neutral share (model) |\n|---|---|---|---|")
        for t in THRESHOLDS:
            m = np.where(X.tone_score > t, 1, np.where(X.tone_score < -t, -1, 0))
            L.append(f"| ±{t:.2f} | {np.mean(m == X.h_tone.astype(int)):.3f} | "
                     f"{cohen_kappa(X.h_tone.astype(int), m):.3f} | {np.mean(m == 0):.3f} |")
        L.append("")
        for lang, g in X.groupby("lang"):
            if len(g) >= 15:
                m = np.where(g.tone_score > 0.15, 1, np.where(g.tone_score < -0.15, -1, 0))
                L.append(f"- {lang}: n={len(g)}, accuracy at ±0.15 = {np.mean(m == g.h_tone.astype(int)):.3f}")
    L.append("\nReading guide: alpha or kappa of about 0.67 to 0.8 is the range papers usually give for tentative conclusions; "
             "below that the labels are too inconsistent to calibrate against until the guide is clarified.")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
